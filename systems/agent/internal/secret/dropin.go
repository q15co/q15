package secret

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"

	"github.com/q15co/q15/systems/agent/internal/atomicfile"
)

// DropInFileName is the file this package writes into podman's drop-in
// directory. It is q15's own file, which is what makes registering the driver a
// drop-in rather than an edit: podman reads every file under containers.conf.d/
// in addition to the user's containers.conf, so the user's file is never
// touched.
const DropInFileName = "q15-secrets.conf"

// dropInMode is the mode a drop-in is left with. It holds no secret, only the
// commands that reach one, so it is as readable as the unit files are.
const dropInMode = 0o644

const dropInHeader = `# Generated by q15. Edit the stack, not this file: re-run the command that
# wrote it and this file is replaced.
#
# This registers q15 as podman's shell secret driver, so a secret created
# through podman is stored by q15 in a sealed store rather than in podman's
# own. Every command below is run as ` + "`<shell> -c <command>`" + ` and is handed the
# secret's identifier in SECRET_ID, except list.
`

// DriverDropIn renders the drop-in that registers a driver command as podman's
// shell secret driver.
//
// prefix is the command that reaches the driver, for example
// {"/usr/local/bin/q15", "secret-driver"}, and extra carries the flags the
// driver needs so that the registered command describes the same store the
// operator wrote to. The first element has to be an absolute path, because
// podman runs each command through a shell whose PATH is not ours and has no
// reason to contain the binary.
func DriverDropIn(prefix []string, extra ...string) ([]byte, error) {
	if len(prefix) == 0 {
		return nil, errors.New("secret: a driver command is required")
	}
	if !filepath.IsAbs(prefix[0]) {
		return nil, fmt.Errorf(
			"secret: %q is not an absolute path, and podman runs the driver through a shell",
			prefix[0],
		)
	}

	driver := make([]string, 0, len(prefix)+len(extra)+1)
	for _, word := range append(append([]string(nil), prefix...), extra...) {
		driver = append(driver, ShellWord(word))
	}
	registered := strings.Join(driver, " ")

	var out bytes.Buffer
	out.WriteString(dropInHeader)
	out.WriteString("\n[secrets]\ndriver = \"shell\"\n\n[secrets.opts]\n")
	for _, verb := range DriverVerbs {
		fmt.Fprintf(&out, "%s = \"%s %s\"\n", verb, registered, verb)
	}
	return out.Bytes(), nil
}

// WriteDropIn writes the drop-in when its contents differ, and reports whether
// it wrote. A drop-in that is already right is left untouched, so running the
// same command twice does not rewrite a file podman may be reading, and the
// second run is a no-op the operator can see.
func WriteDropIn(path string, contents []byte) (bool, error) {
	existing, err := os.ReadFile(path)
	switch {
	case err == nil && bytes.Equal(existing, contents):
		return false, nil
	case err != nil && !errors.Is(err, fs.ErrNotExist):
		return false, fmt.Errorf("secret: read %s: %w", path, err)
	}

	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return false, fmt.Errorf("secret: create %s: %w", filepath.Dir(path), err)
	}
	if err := atomicfile.WriteBytes(path, contents); err != nil {
		return false, err
	}
	if err := os.Chmod(path, dropInMode); err != nil {
		return false, fmt.Errorf("secret: chmod %s: %w", path, err)
	}
	return true, nil
}

// DefaultDropInPath is where the drop-in belongs: a file of q15's own inside
// podman's drop-in directory.
func DefaultDropInPath() (string, error) {
	dir := strings.TrimSpace(os.Getenv("XDG_CONFIG_HOME"))
	if dir == "" {
		home, err := os.UserHomeDir()
		if err != nil {
			return "", fmt.Errorf("secret: resolve the user's home: %w", err)
		}
		dir = filepath.Join(home, ".config")
	}
	return filepath.Join(dir, "containers", "containers.conf.d", DropInFileName), nil
}
